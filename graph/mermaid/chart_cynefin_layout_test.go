package mermaid

import (
	"math"
	"testing"
)

// TestCynefinBoundaries checks the paths of the boundaries of a Cynefin
// diagram against the SVG of mmdc 12.3.0, which draws them from a seed: 42
// from cynefin.seed, or the hash of the id of the SVG of mmdc when the
// seed is 0.
func TestCynefinBoundaries(t *testing.T) {
	t.Parallel()
	const (
		fold42 = "M401.6176600307226,0 C406.1051963418722,42.857142857142854 393.83792743459344,42.857142857142854 398.32546374574304,85.71428571428571 " +
			"C388.9074451420456,128.57142857142856 408.5978268850595,128.57142857142856 399.17980828136206,171.42857142857142 " +
			"C411.061179228127,214.28571428571428 384.1414481513202,214.28571428571428 396.02281909808517,257.1428571428571 " +
			"C388.19614854827523,300 401.8663558997214,300 394.03968534991145,342.85714285714283 " +
			"C394.646731027402,385.71428571428567 395.26246194075793,385.71428571428567 395.86950761824846,428.57142857142856 " +
			"C388.7759249135852,471.4285714285714 400.10278279706836,471.4285714285714 393.0092000924051,514.2857142857142 " +
			"C397.820225157775,557.1428571428571 391.8345404965803,557.1428571428571 396.6455655619502,600"
		cross42 = "M0,302.4355607330799 C57.142857142857146,303.3416154226288 57.142857142857146,300.1904623778537 114.28571428571429,301.0965170674026 " +
			"C171.42857142857144,295.0789345977828 171.42857142857144,307.64793300721794 228.57142857142858,301.63035053759813 " +
			"C285.7142857142857,309.4184307185933 285.7142857142857,287.4359616795555 342.8571428571429,295.22404186055064 " +
			"C400,287.4545803312212 400,306.18829846940935 457.14285714285717,298.4188369400799 " +
			"C514.2857142857143,304.3443540688604 514.2857142857143,289.791006622836 571.4285714285714,295.7165237516165 " +
			"C628.5714285714287,294.0327402036637 628.5714285714287,300.320102667436 685.7142857142858,298.63631911948323 " +
			"C742.8571428571429,302.2020494295284 742.8571428571429,303.34077848587185 800,306.90650879591703"
		cliff = "M400,300 C424,360 364,465 412,525 C376,555 407.2,585 400,600"
		// foldDefault is the fold of mmdc with no seed, from the hash of
		// the id my-svg.
		foldDefault = "M404.8574703261256,0 C415.3262379048392,42.857142857142854 383.91018708143383,42.857142857142854 394.37895466014743,85.71428571428571 " +
			"C391.4765734700486,128.57142857142856 403.71889816690236,128.57142857142856 400.81651697680354,171.42857142857142 " +
			"C409.75660386215895,214.28571428571428 393.6235443139449,214.28571428571428 402.5636311993003,257.1428571428571 " +
			"C394.20219630002975,300 402.28042075783014,300 393.9189858585596,342.85714285714283 " +
			"C405.19507957529277,385.71428571428567 389.8323155315593,385.71428571428567 401.10840924829245,428.57142857142856 " +
			"C396.10414875112474,471.4285714285714 403.98664483986795,471.4285714285714 398.98238434270024,514.2857142857142 " +
			"C410.10545024555176,557.1428571428571 394.4031163873151,557.1428571428571 405.5261822901666,600"
	)
	cases := []struct {
		name, got, want string
	}{
		{"fold 42", cyFold(800, 600, 42, 8), fold42},
		{"cross 42", cyCross(800, 600, 142, 8), cross42},
		{"cliff", cyCliff(800, 600), cliff},
		{"fold", cyFold(800, 600, float64(cyHash(cyDefaultID)), 8), foldDefault},
	}
	for _, c := range cases {
		got, want := gitNumbers(c.got), gitNumbers(c.want)
		if len(got) != len(want) {
			t.Errorf("%s: %d numbers, expected %d", c.name, len(got), len(want))
			continue
		}
		for i := range got {
			if math.Abs(got[i]-want[i]) > 0.006 {
				t.Errorf("%s: number %d is %v, expected %v", c.name, i, got[i], want[i])
				break
			}
		}
	}
	// With an amplitude of 0, a boundary is a straight line.
	nums := gitNumbers(cyFold(800, 600, 42, 0))
	for i := 0; i < len(nums); i += 2 {
		if nums[i] != 400 {
			t.Errorf("a straight fold at x %v", nums[i])
		}
	}
}
