// gen-data.mjs writes data.js, the data of compare.html.
//
// The data is real. It is a copy of twelve files of vega-datasets, which is
// under the BSD-3-Clause license. Each library on the page draws the same
// rows, so a difference on the page is a difference of the library. The
// targets in docs/targets read the same file.
//
// Run it with the folder that holds the files:
//
//	node gen-data.mjs DIR > data.js
//
// Fetch the files with:
//
//	for f in stocks.csv cars.json seattle-weather.csv ohlc.json flare.json \
//	  us-10m.json population_engineers_hurricanes.csv barley.json penguins.json \
//	  gapminder.json miserables.json flare-dependencies.json; do
//	  curl -sfO https://cdn.jsdelivr.net/npm/vega-datasets@3.3.1/data/$f
//	done
import { readFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node gen-data.mjs DIR > data.js");
  process.exit(2);
}

const read = (name) => readFileSync(join(dir, name), "utf8");
const json = (name) => JSON.parse(read(name));

// csv reads a file with no quoted fields, and makes a number of each field
// that reads as one.
const csv = (name) => {
  const [head, ...lines] = read(name).trim().split(/\r?\n/);
  const keys = head.split(",");
  return lines.map((line) => {
    const cells = line.split(",");
    const row = {};
    keys.forEach((k, i) => {
      const n = Number(cells[i]);
      row[k] = cells[i] !== "" && !Number.isNaN(n) ? n : cells[i];
    });
    return row;
  });
};

// The topology keeps the states and the land, and drops the counties, which
// no chart on the page draws.
const us = json("us-10m.json");
delete us.objects.counties;

const data = {
  source: "vega-datasets 3.3.1, https://github.com/vega/vega-datasets, BSD-3-Clause",
  stocks: csv("stocks.csv"),
  cars: json("cars.json"),
  weather: csv("seattle-weather.csv"),
  ohlc: json("ohlc.json"),
  flare: json("flare.json"),
  us,
  states: csv("population_engineers_hurricanes.csv"),
  barley: json("barley.json"),
  penguins: json("penguins.json"),
  gapminder: json("gapminder.json"),
  miserables: json("miserables.json"),
  flareDeps: json("flare-dependencies.json"),
};

process.stdout.write("// Generated by gen-data.mjs from " + data.source + ". Do not edit.\n");
process.stdout.write("window.SURVEY_DATA = " + JSON.stringify(data) + ";\n");
